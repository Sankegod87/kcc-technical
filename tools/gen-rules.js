// Builds firestore.rules from kcc-schema.js so the rules and the app can never disagree.
//   node tools/gen-rules.js        (writes firestore.rules)
const S = require('../kcc-schema.js');
const q = a => '[' + a.map(k => "'" + k + "'").join(', ') + ']';
const out = `// GENERATED by tools/gen-rules.js from kcc-schema.js. Do not edit by hand.
// NOT DEPLOYED. These rules need the Cloud Functions login (kcc-auth.js) to be live first,
// otherwise nobody can sign in. See DEPLOY-SERVER-LOGIN.md.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {

    // Signed in through the "login" Cloud Function. The token carries r (user/admin/master) and cs (can schedule).
    function signedIn() { return request.auth != null && request.auth.token.r in ['user', 'admin', 'master']; }
    function isAdmin()  { return signedIn() && request.auth.token.r in ['admin', 'master']; }
    function canSched() { return isAdmin() || (signedIn() && request.auth.token.cs == true); }

    // One app data document: { p: JSON text, n: save id, t: server time }
    function shapeOk() {
      return request.resource.data.keys().hasOnly(['p', 'n', 't'])
          && request.resource.data.p is string
          && request.resource.data.p.size() < 900000
          && request.resource.data.n is string
          && request.resource.data.n.size() < 80;
    }

    // Names on the sign-in screen (id, first name, avatar, department). Nothing secret. Written by Cloud Functions only.
    match /pub/roster {
      allow read: if true;
      allow write: if false;
    }

    match /data/{key} {
      allow read: if signedIn() && key in ${q(S.ALL)};
      allow create, update: if shapeOk() && (
           (key in ${q(S.TIERS.open)} && signedIn())
        || (key in ${q(S.TIERS.sched)} && canSched())
        || (key in ${q(S.TIERS.admin)} && isAdmin()));
      allow delete: if false;
      // ${S.TIERS.server.join(', ')}: Cloud Functions only (no client rule matches, so writes are refused)
    }

    // Password hashes, lockout counters, API keys, rate limits: Cloud Functions only.
    match /{document=**} {
      allow read, write: if false;
    }
  }
}
`;
require('fs').writeFileSync(require('path').join(__dirname, '..', 'firestore.rules'), out);
console.log('wrote firestore.rules');
